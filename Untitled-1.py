def get_personalized_workout(weight, height, age, fitness_level):
    """
    Підбирає персоналізований курс тренувань на основі показників користувача.
    """

    # Перевірка коректності введених даних
    if not (30 <= weight <= 300):
        return {"помилка": "Вага повинна бути в межах 30–300 кг"}
    if not (100 <= height <= 250):
        return {"помилка": "Ріст повинен бути в межах 100–250 см"}
    if not (5 <= age <= 120):
        return {"помилка": "Вік повинен бути в межах 5–120 років"}
    if fitness_level.lower() not in ["низький", "середній", "високий"]:
        return {"помилка": "Рівень фітнесу має бути: низький, середній або високий"}

    # Список вправ
    all_exercises = {
        'присідання': {'напруга': 'середня', 'якість': 'ноги'},
        'віджимання': {'напруга': 'висока', 'якість': 'верхня частина'},
        'стрибки': {'напруга': 'висока', 'якість': 'ноги'},
        'біг': {'напруга': 'висока', 'якість': 'кардіо'},
        'планка': {'напруга': 'середня', 'якість': 'кор'},
        'скручування': {'напруга': 'низька', 'якість': 'кор'},
        'йога': {'напруга': 'низька', 'якість': 'гнучкість'},
        'розтягування': {'напруга': 'низька', 'якість': 'гнучкість'},
        'відведення ніг': {'напруга': 'низька', 'якість': 'ноги'},
        'випади на одній нозі': {'напруга': 'висока', 'якість': 'ноги'},
        'підтримання ваги': {'напруга': 'висока', 'якість': 'верхня частина'},
        'прес лежачи': {'напруга': 'низька', 'якість': 'спина'},
    }

    low_level = ['розтягування', 'скручування', 'йога', 'планка', 'біг']
    medium_level = ['присідання', 'віджимання', 'біг', 'планка', 'випади на одній нозі', 'розтягування']
    high_level = ['присідання', 'віджимання', 'стрибки', 'біг', 'випади на одній нозі', 'підтримання ваги', 'планка']

    if fitness_level.lower() == 'низький':
        recommended = low_level
        repetitions = {'присідання': 10, 'віджимання': 5, 'стрибки': 5, 'біг': '5 хв', 'планка': '15 сек', 'розтягування': '30 сек', 'скручування': 10, 'йога': '10 хв'}
        duration = '20 хвилин'
    elif fitness_level.lower() == 'середній':
        recommended = medium_level
        repetitions = {'присідання': 15, 'віджимання': 10, 'стрибки': 10, 'біг': '10 хв', 'планка': '30 сек', 'розтягування': '30 сек', 'випади на одній нозі': 8}
        duration = '40 хвилин'
    else:  # високий
        recommended = high_level
        repetitions = {'присідання': 20, 'віджимання': 15, 'стрибки': 20, 'біг': '20 хв', 'планка': '1 хв', 'випади на одній нозі': 15, 'підтримання ваги': 5}
        duration = '60 хвилин'

    bmi = round(weight / ((height / 100) ** 2), 2)

    workout_plan = {
        'показники': {
            'вага': weight,
            'ріст': height,
            'вік': age,
            'BMI': bmi,
            'рівень_фітнесу': fitness_level
        },
        'рекомендоване_тренування': recommended,
        'кількість_повторень': {ex: repetitions.get(ex, 'за відчуттям') for ex in recommended},
        'загальна_тривалість': duration,
        'примітки': []
    }

    if age < 18:
        workout_plan['примітки'].append('⚠️ Молодий вік: зосередьтесь на техніці без надмірного навантаження')
    elif age > 60:
        workout_plan['примітки'].append('⚠️ Старший вік: більш легкі вправи з акцентом на гнучкість')

    if bmi < 18.5:
        workout_plan['примітки'].append('⚠️ Низька вага: збільшіть калорійність харчування')
    elif bmi > 30:
        workout_plan['примітки'].append('⚠️ Підвищена вага: акцент на кардіо вправи')

    return workout_plan


if __name__ == "__main__":
    try:
        weight = float(input("Введіть вашу вагу (кг): "))
        height = float(input("Введіть ваш ріст (см): "))
        age = int(input("Введіть ваш вік (роки): "))
        fitness_level = input("Введіть рівень фітнесу (низький/середній/високий): ")

        plan = get_personalized_workout(weight, height, age, fitness_level)
        print("\nВаш персоналізований план тренувань:")
        print(plan)
    except ValueError:
        print("❌ Помилка: введіть числові значення для ваги, росту та віку.")